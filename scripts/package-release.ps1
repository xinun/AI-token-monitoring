기존 0.1.0 사용자는 앱을 종료하고 이 설치 파일을 한 번 직접 실행해야 합니다.
새 버전 알림에서 '릴리즈 페이지 보기'로 직접 다운로드하거나 '업데이트 설치'를 선택할 수 있습니다.
'승인하고 설치'를 눌러야 파일 다운로드, 서명 검증과 설치를 시작합니다.
포터블 ZIP은 압축 해제 후 실행할 수 있지만 자동 업데이트에는 설치형을 사용하세요.

1. ZIP을 원하는 폴더에 압축 해제합니다.
2. ai-token.exe를 실행합니다.
3. 작업표시줄 오른쪽 AI Token 아이콘을 클릭하면 상세 창이 열립니다.
