AI Token은 각 AI 서비스와 제휴하지 않은 독립 앱입니다.
서비스 아이콘의 출처는 BRAND_ASSETS.md, 앱 라이선스는 LICENSE를 확인하세요.
"@
$utf8 = New-Object Text.UTF8Encoding($false)
[IO.File]::WriteAllText($readmePath, $readme, $utf8)

$archivePath = Join-Path $releaseRoot ($archiveStem + '.zip')
# Zip the fresh build input; an identical EXE may still be running from the portable output folder.
Compress-Archive -LiteralPath @($binary, $readmePath, $brandsPath, $licensePath) -DestinationPath $archivePath -Force

$outputInstallerName = $archiveStem + '-setup.exe'
$outputInstaller = Join-Path $releaseRoot $outputInstallerName
$outputSignature = $outputInstaller + '.sig'
Copy-Item -LiteralPath $installer -Destination $outputInstaller -Force
Copy-Item -LiteralPath $installerSignature -Destination $outputSignature -Force

$manifest = [ordered]@{
    version = $packageVersion
    notes = $Notes
    pub_date = [DateTimeOffset]::UtcNow.ToString('yyyy-MM-ddTHH:mm:ssZ')
    platforms = [ordered]@{
        'windows-x86_64' = [ordered]@{
            url = 'https://github.com/xinun/AI-token-monitoring/releases/download/v' + $packageVersion + '/' + $outputInstallerName
            signature = $signature
        }
    }
}
$manifestPath = Join-Path $releaseRoot 'latest.json'
[IO.File]::WriteAllText($manifestPath, ($manifest | ConvertTo-Json -Depth 6), $utf8)

Get-Item -LiteralPath $outputInstaller, $outputSignature, $manifestPath, $archivePath | Select-Object FullName, Length
