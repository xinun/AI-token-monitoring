param(
    [string]$Notes = '앱 내 새 버전 알림, 릴리즈 페이지 보기와 사용자 승인 후 업데이트 설치를 추가했습니다.'
)

$ErrorActionPreference = 'Stop'
function Get-ReleaseFileHash([string]$Path) {
    $stream = [IO.File]::OpenRead($Path)
    $hasher = [Security.Cryptography.SHA256]::Create()
    try { return [BitConverter]::ToString($hasher.ComputeHash($stream)).Replace('-', '') }
    finally {
        $hasher.Dispose()
        $stream.Dispose()
    }
}

$projectRoot = Split-Path -Parent $PSScriptRoot
$packageVersion = [string](Get-Content -LiteralPath (Join-Path $projectRoot 'package.json') -Raw | ConvertFrom-Json).version
$configuration = Get-Content -LiteralPath (Join-Path $projectRoot 'src-tauri/tauri.conf.json') -Raw | ConvertFrom-Json
$cargoContents = Get-Content -LiteralPath (Join-Path $projectRoot 'src-tauri/Cargo.toml') -Raw
$cargoPackage = [regex]::Match($cargoContents, '(?ms)^\[package\]\s*(?<body>.*?)(?=^\[|\z)').Groups['body'].Value
$cargoVersion = [regex]::Match($cargoPackage, '(?m)^version\s*=\s*"(?<version>[^"]+)"').Groups['version'].Value
if ($packageVersion -notmatch '^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$' -or $packageVersion -ne $configuration.version -or $packageVersion -ne $cargoVersion) {
    throw 'package.json, src-tauri/Cargo.toml, and src-tauri/tauri.conf.json must use the same valid release version.'
}
if ($configuration.bundle.createUpdaterArtifacts -ne $true -or $configuration.plugins.updater.requireSignedVersion -ne $true) {
    throw 'Packaging requires updater artifacts with signatures bound to the app version.'
}

$binary = Join-Path $projectRoot 'src-tauri/target/release/ai-token.exe'
$installerName = [string]$configuration.productName + '_' + $packageVersion + '_x64-setup.exe'
$installer = Join-Path $projectRoot ('src-tauri/target/release/bundle/nsis/' + $installerName)
$installerSignature = $installer + '.sig'
foreach ($requiredFile in @($binary, $installer, $installerSignature, (Join-Path $projectRoot 'BRAND_ASSETS.md'), (Join-Path $projectRoot 'LICENSE'))) {
    if (-not (Test-Path -LiteralPath $requiredFile -PathType Leaf)) {
        throw "Release input missing: $requiredFile. Run npm run build:desktop first."
    }
}

# Select only this version's x64 installer, then verify the signature's version field.
# The updater performs the cryptographic signature verification when downloading.
$signature = (Get-Content -LiteralPath $installerSignature -Raw).Trim()
try { $signatureText = [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($signature)) }
catch { throw 'The installer signature is not a valid Tauri signature.' }
$trustedComment = [regex]::Match($signatureText, '(?m)^trusted comment: (?<comment>[^\r\n]+)').Groups['comment'].Value
$signedVersion = [regex]::Match($trustedComment, '(?:^|\t)version:(?<version>[^\t\r\n]+)(?:\t|$)').Groups['version'].Value
if ($signedVersion -ne $packageVersion) {
    throw 'The installer signature must be generated by tauri build for this exact app version. Do not reuse a previous version signature.'
}
$binaryVersion = (Get-Item -LiteralPath $binary).VersionInfo.ProductVersion
if ($binaryVersion -ne $packageVersion) {
    throw "Release executable version '$binaryVersion' does not match $packageVersion. Rebuild the desktop app."
}

$archiveStem = 'AI-Token-' + $packageVersion + '-windows-x64'
$releaseRoot = Join-Path $projectRoot 'release'
$packageRoot = Join-Path $releaseRoot $archiveStem
New-Item -ItemType Directory -Path $packageRoot -Force | Out-Null
$outputBinary = Join-Path $packageRoot 'ai-token.exe'
$readmePath = Join-Path $packageRoot 'README.txt'
$brandsPath = Join-Path $packageRoot 'BRAND_ASSETS.md'
$licensePath = Join-Path $packageRoot 'LICENSE'
$sourceHash = Get-ReleaseFileHash $binary
$destinationUnchanged = (Test-Path -LiteralPath $outputBinary -PathType Leaf) -and (Get-ReleaseFileHash $outputBinary) -eq $sourceHash
if (-not $destinationUnchanged) {
    try { Copy-Item -LiteralPath $binary -Destination $outputBinary -Force }
    catch {
        throw "Cannot replace $outputBinary. Close AI Token running from the release folder, then run scripts/package-release.ps1 again. $($_.Exception.Message)"
    }
}
Copy-Item -LiteralPath (Join-Path $projectRoot 'BRAND_ASSETS.md') -Destination $brandsPath -Force
Copy-Item -LiteralPath (Join-Path $projectRoot 'LICENSE') -Destination $licensePath -Force

$readme = @"
