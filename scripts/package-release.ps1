param([string]$Notes = '')

$ErrorActionPreference = 'Stop'
$projectRoot = [IO.Path]::GetFullPath((Split-Path -Parent $PSScriptRoot))
$packageVersion = [string](Get-Content -LiteralPath (Join-Path $projectRoot 'package.json') -Raw -Encoding UTF8 | ConvertFrom-Json).version
$configuration = Get-Content -LiteralPath (Join-Path $projectRoot 'src-tauri/tauri.conf.json') -Raw -Encoding UTF8 | ConvertFrom-Json
$cargoContents = Get-Content -LiteralPath (Join-Path $projectRoot 'src-tauri/Cargo.toml') -Raw -Encoding UTF8
$cargoPackage = [regex]::Match($cargoContents, '(?ms)^\[package\]\s*(?<body>.*?)(?=^\[|\z)').Groups['body'].Value
$cargoVersion = [regex]::Match($cargoPackage, '(?m)^version\s*=\s*"(?<version>[^"]+)"').Groups['version'].Value
if ($packageVersion -notmatch '^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$' -or $packageVersion -ne $configuration.version -or $packageVersion -ne $cargoVersion) {
    throw 'package.json, src-tauri/Cargo.toml, and src-tauri/tauri.conf.json must use the same valid release version.'
}
if ($configuration.bundle.createUpdaterArtifacts -ne $true -or $configuration.plugins.updater.requireSignedVersion -ne $true) {
    throw 'Packaging requires updater artifacts with signatures bound to the app version.'
}

$binary = Join-Path $projectRoot 'src-tauri/target/release/ai-token.exe'
$installerName = [string]$configuration.productName + '_' + $packageVersion + '_x64-setup.exe'
$installer = Join-Path $projectRoot ('src-tauri/target/release/bundle/nsis/' + $installerName)
$installerSignature = $installer + '.sig'
$brandCredits = Join-Path $projectRoot 'BRAND_ASSETS.md'
$license = Join-Path $projectRoot 'LICENSE'
foreach ($required in @($binary, $installer, $installerSignature, $brandCredits, $license)) {
    if (-not (Test-Path -LiteralPath $required -PathType Leaf)) { throw "Release input missing: $required. Run npm run build:desktop first." }
}

# The generated sidecar is read only while packaging. The client uses the
# signature embedded in latest.json, so no separate .sig upload is required.
$signature = (Get-Content -LiteralPath $installerSignature -Raw -Encoding UTF8).Trim()
try { $signatureText = [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($signature)) }
catch { throw 'The installer signature is not a valid Tauri signature.' }
$trustedComment = [regex]::Match($signatureText, '(?m)^trusted comment: (?<comment>[^\r\n]+)').Groups['comment'].Value
$signedVersion = [regex]::Match($trustedComment, '(?:^|\t)version:(?<version>[^\t\r\n]+)(?:\t|$)').Groups['version'].Value
if ($signedVersion -ne $packageVersion) { throw 'The signature must be generated by tauri build for this exact app version.' }
if ((Get-Item -LiteralPath $binary).VersionInfo.ProductVersion -ne $packageVersion) { throw 'The executable version does not match the package version. Rebuild the desktop app.' }

if ([string]::IsNullOrWhiteSpace($Notes)) {
    $changelog = Get-Content -LiteralPath (Join-Path $projectRoot 'CHANGELOG.md') -Raw -Encoding UTF8
    $section = '(?ms)^##\s+' + [regex]::Escape($packageVersion) + '\s*\r?\n(?<notes>.*?)(?=^##\s|\z)'
    $Notes = [regex]::Match($changelog, $section).Groups['notes'].Value.Trim()
    if ([string]::IsNullOrWhiteSpace($Notes)) { $Notes = 'AI Token ' + $packageVersion }
}

$releaseRoot = [IO.Path]::GetFullPath((Join-Path $projectRoot 'release'))
$packageRoot = [IO.Path]::GetFullPath((Join-Path $releaseRoot $packageVersion))
if (-not $packageRoot.StartsWith($releaseRoot + '\', [StringComparison]::OrdinalIgnoreCase)) { throw 'Release path outside the release directory.' }
New-Item -ItemType Directory -Path $packageRoot -Force | Out-Null
$archiveStem = 'AI-Token-' + $packageVersion + '-windows-x64'
$outputInstaller = Join-Path $packageRoot ($archiveStem + '-setup.exe')
$archivePath = Join-Path $packageRoot ($archiveStem + '.zip')
$manifestPath = Join-Path $packageRoot 'latest.json'
$utf8 = New-Object Text.UTF8Encoding($false)

$scratchParent = [IO.Path]::GetFullPath((Join-Path $projectRoot 'src-tauri/target'))
$scratch = [IO.Path]::GetFullPath((Join-Path $scratchParent ('package-' + [Guid]::NewGuid().ToString('N'))))
if ([IO.Path]::GetDirectoryName($scratch) -ne $scratchParent) { throw 'Unexpected packaging scratch path.' }
New-Item -ItemType Directory -Path $scratch | Out-Null
try {
    $readmePath = Join-Path $scratch 'README.txt'
    $readme = @"
AI Token $packageVersion - Windows x64

ZIP을 압축 해제하고 ai-token.exe를 실행하세요. 트레이 아이콘을 클릭하면 상세 창이 열립니다.
미니바에 표시할 AI와 로그인 시 자동 실행 여부는 연결 설정에서 선택할 수 있습니다.

앱 내 업데이트 설치를 사용하려면 GitHub 릴리즈의 $archiveStem-setup.exe로 설치하세요.
업데이트는 '승인하고 설치'를 눌렀을 때만 다운로드하고 적용합니다.
0.1.0 사용자는 설치 파일을 처음 한 번 직접 실행해야 합니다.

환경: Windows 10/11 x64, Microsoft Edge WebView2 Runtime.
Codex: 이 PC에 설치되고 로그인된 Codex CLI가 필요합니다.
Claude Code: 앱 설정의 '이 PC용 명령'으로 별도 연결합니다.
Antigravity/Grok: 아직 한도 조회를 지원하지 않습니다.

잔여값은 구독 한도의 비율이며 정확한 토큰 수가 아닙니다.
ZIP에는 개인 설정이나 로그인 인증 정보를 포함하지 않습니다.
서비스 아이콘 출처는 BRAND_ASSETS.md, 앱 라이선스는 LICENSE를 확인하세요.
"@
    [IO.File]::WriteAllText($readmePath, $readme, $utf8)
    # Compress fresh inputs directly; never keep a duplicate unpacked EXE folder.
    Compress-Archive -LiteralPath @($binary, $readmePath, $brandCredits, $license) -DestinationPath $archivePath -Force
    Copy-Item -LiteralPath $installer -Destination $outputInstaller -Force
    $manifest = [ordered]@{
        version = $packageVersion
        notes = $Notes
        pub_date = [DateTimeOffset]::UtcNow.ToString('yyyy-MM-ddTHH:mm:ssZ')
        platforms = [ordered]@{
            'windows-x86_64' = [ordered]@{
                url = 'https://github.com/xinun/AI-token-monitoring/releases/download/v' + $packageVersion + '/' + $archiveStem + '-setup.exe'
                signature = $signature
            }
        }
    }
    [IO.File]::WriteAllText($manifestPath, ($manifest | ConvertTo-Json -Depth 6), $utf8)
} finally {
    $resolved = (Resolve-Path -LiteralPath $scratch).ProviderPath
    if ($resolved -ne $scratch -or [IO.Path]::GetDirectoryName($resolved) -ne $scratchParent -or ((Get-Item -LiteralPath $resolved).Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
        throw 'Refusing cleanup of an unexpected packaging path.'
    }
    Remove-Item -LiteralPath $resolved -Recurse -Force
}

Get-Item -LiteralPath $outputInstaller, $manifestPath, $archivePath | Select-Object FullName, Length
